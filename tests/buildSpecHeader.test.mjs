// Test 5: parseSpecHeader with NEW 1.1 format (sources array round-trip)
test('parseSpecHeader: 새 1.1 포맷 파싱 (sources 배열 라운드트립)', () => {
  const md = `<!-- Generated by figma-ux-spec@0.3.0 at 2026-05-27T10:00:00Z -->
<!-- status: finalized -->
<!-- sources: figma:235:1412@design, markdown:./req.md -->
<!-- specVersion: 1.1 -->

# Requirements: LoginPage
...`;
  const parsed = parseSpecHeader(md);
  assert.ok(parsed, 'Should parse header');
  assert.equal(parsed.brand, 'figma-ux-spec', 'brand is figma-ux-spec');
  assert.equal(parsed.pluginVersion, '0.3.0');
  assert.equal(parsed.generatedAt, '2026-05-27T10:00:00Z');
  assert.equal(parsed.status, 'finalized');
  assert.equal(parsed.specVersion, '1.1');
  // WHY: sources is an array with type, locator, and optional role fields
  assert.ok(Array.isArray(parsed.sources), 'sources should be array');
  assert.equal(parsed.sources.length, 2);
  assert.deepEqual(parsed.sources[0], { type: 'figma', locator: '235:1412', role: 'design' });
  assert.deepEqual(parsed.sources[1], { type: 'markdown', locator: './req.md' });
});

// Test 6: parseSpecHeader with OLD 1.0 format (backward compatibility + migration)
test('parseSpecHeader: 이전 1.0 포맷 파싱 및 마이그레이션', () => {
  const md = `<!-- Generated by figma-ux-spec@0.1.0 at 2026-05-27T10:00:00Z -->
<!-- status: finalized -->
<!-- sources: figmaPageNodeId=1:234, figmaUxWireframeNodeId=2:456 -->
<!-- specVersion: 1.0 -->

# Requirements: LoginPage
...`;
  const parsed = parseSpecHeader(md);
  assert.ok(parsed, 'Should parse 1.0 header');
  assert.equal(parsed.brand, 'figma-ux-spec');
  assert.equal(parsed.pluginVersion, '0.1.0');
  assert.equal(parsed.generatedAt, '2026-05-27T10:00:00Z');
  assert.equal(parsed.status, 'finalized');
  assert.equal(parsed.specVersion, '1.0');
  // WHY: 1.0 format migrated to sources array with design/wireframe roles
  assert.ok(Array.isArray(parsed.sources), 'sources should be normalized to array');
  assert.equal(parsed.sources.length, 2);
  assert.deepEqual(parsed.sources[0], { type: 'figma', locator: '1:234', role: 'design' });
  assert.deepEqual(parsed.sources[1], { type: 'figma', locator: '2:456', role: 'wireframe' });
});

// Test 7: parseSpecHeader accepts dt-spec@ brand (forward-compat)
test('parseSpecHeader: dt-spec@ 브랜드도 수용 (상위호환성)', () => {
  const md = `<!-- Generated by dt-spec@1.0.0 at 2026-05-27T10:00:00Z -->
<!-- status: draft -->
<!-- sources: figma:100:200@design, web:https://notion.so/x (load-failed) -->
<!-- specVersion: 1.1 -->

# Page spec`;
  const parsed = parseSpecHeader(md);
  assert.ok(parsed, 'Should parse dt-spec@ brand');
  assert.equal(parsed.brand, 'dt-spec', 'brand is dt-spec');
  assert.equal(parsed.pluginVersion, '1.0.0');
  assert.equal(parsed.status, 'draft');
  assert.equal(parsed.specVersion, '1.1');
  assert.equal(parsed.sources.length, 2);
  assert.deepEqual(parsed.sources[0], { type: 'figma', locator: '100:200', role: 'design' });
  // WHY: loadFailed is true when (load-failed) is present in sources string
  assert.deepEqual(parsed.sources[1], { type: 'web', locator: 'https://notion.so/x', loadFailed: true });
});

