import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  buildSpecHeader,
  parseSpecHeader,
  PLUGIN_VERSION
} from '../scripts/buildSpecHeader.mjs';

// Test 1: PLUGIN_VERSION consistency
test('PLUGIN_VERSION: plugin.json과 일치', async () => {
  const { readFile } = await import('node:fs/promises');
  const pkg = JSON.parse(await readFile(new URL('../.claude-plugin/plugin.json', import.meta.url)));
  assert.equal(PLUGIN_VERSION, pkg.version);
});

// Test 2: buildSpecHeader with sources array (new multi-source format)
test('buildSpecHeader: sources 배열로 다중 소스 지원 (1.1 포맷)', () => {
  const out = buildSpecHeader({
    generatedAt: '2026-05-27T10:00:00Z',
    status: 'finalized',
    sources: [
      { type: 'figma', locator: '235:1412', role: 'design' },
      { type: 'markdown', locator: './req.md' }
    ]
  });
  const lines = out.split('\n');
  assert.equal(lines.length, 4, 'Should have 4 lines');
  assert.match(lines[0], /<!-- Generated by dt-spec@/, 'Line 0: brand is dt-spec@');
  assert.match(lines[0], / at 2026-05-27T10:00:00Z -->/, 'Line 0: has generatedAt');
  assert.equal(lines[1], '<!-- status: finalized -->', 'Line 1: status');
  // WHY: sources line contains multi-source comma-space-joined, with role suffix and optional loadFailed note
  assert.equal(lines[2], '<!-- sources: figma:235:1412@design, markdown:./req.md -->', 'Line 2: sources format');
  assert.equal(lines[3], '<!-- specVersion: 1.1 -->', 'Line 3: specVersion 1.1');
});

