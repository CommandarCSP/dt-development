const tmpl = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');

test('setMarker·readMarker: 앞머리 주석 뒤에 붙이고, 다시 붙이면 바꾼다(한 번만)', () => {
  const md = '<!-- a -->\n<!-- b -->\n# 제목\n본문\n';
  const once = setMarker(md, 'plan', 1);
  assert.equal(once, '<!-- a -->\n<!-- b -->\n<!-- dt-schema: plan@1 -->\n# 제목\n본문\n');
  assert.deepEqual(readMarker(once), { kind: 'plan', version: 1 });
  assert.equal(setMarker(setMarker(once, 'plan', 2), 'plan', 2).match(/dt-schema/g).length, 1);
  const fm = setMarker('---\nid: PD-001\n---\n# 결정\n', 'decision', 1);
  assert.ok(fm.startsWith('---\nid: PD-001\n---\n<!-- dt-schema: decision@1 -->\n'), '머리말 뒤에 둔다');
});

test('새로 만드는 산출물은 현재 형식 표시를 단다(템플릿·작성 도구)', () => {
  for (const p of ['templates/project-context.md.tmpl', 'templates-backend/project-context.md.tmpl']) assert.match(tmpl(p), /dt-schema: project-context@2/);
  assert.match(tmpl('templates/decision.md.tmpl'), /dt-schema: decision@1/);
  assert.match(PREAMBLE, /dt-schema: interactions@2/);
  assert.equal(buildStackConfig('frontend', { srcPath: 'src' }).$schemaVersion, 1);
  assert.equal(JSON.parse(tmpl('skills/dt-wrap/references/dt.example.json')).$schemaVersion, 1);
  for (const [p, kind] of [['docs/project-context.md', 'project-context'], ['docs/specs/interactions.md', 'interactions']]) {
    const s = schemaFor(p);
    assert.equal(s.kind, kind);
    const sample = kind === 'interactions' ? PREAMBLE + '## FE 크로스페이지\n### 네비\n- a\n' : tmpl('templates/project-context.md.tmpl');
    assert.equal(s.detect(sample, {}).status, 'current', `${kind} 템플릿은 현재 형식`);
  }
});

test('판정: 스펙 specVersion·정의서·설정 $schemaVersion — 옛것·현재·더 새것', () => {
  const spec = (v) => `<!-- Generated by dt-spec@0.14.0 at 2026-01-01T00:00:00Z -->\n<!-- status: draft -->\n<!-- sources: md:a.md -->\n<!-- specVersion: ${v} -->\n# R\n`;
  const s = schemaFor('docs/specs/pages/home/requirements.md');
  assert.equal(s.detect(spec('1.1')).status, 'current');
  assert.equal(s.detect(spec('1.0')).status, 'manual');
  assert.equal(s.detect(spec('9.0')).status, 'newer');
  assert.equal(s.detect('# 손으로 쓴 스펙\n').status, 'manual');
  const c = schemaFor('.dt.json');
  assert.equal(c.detect('{"team":{}}').status, 'current', '표시가 없으면 현재로 본다');
  assert.equal(c.detect('{"$schemaVersion": 2}').status, 'newer');
  assert.equal(schemaFor('src/app.ts'), null);
});

function project(files) {
  const root = mkdtempSync(join(tmpdir(), 'dt-mig-'));
  for (const [p, body] of Object.entries(files)) { mkdirSync(dirname(join(root, p)), { recursive: true }); writeFileSync(join(root, p), body); }
  return root;
}
const OLD_PC = '# Project Context\n\n## Overview\n앱.\n\n## Tech Stack\n- React, SCSS\n';
const OLD_INTER = '# Interactions\n\n## 네비 그래프\n- a → b\n';

test('migrate: 옛 project-context·interactions 를 찾아 옮기고, 다시 돌리면 할 일이 없다', () => {
  const root = project({
    'package.json': '{"dependencies":{"react":"19"}}',
    'docs/project-context.md': OLD_PC,
    'docs/specs/interactions.md': OLD_INTER,
    'docs/specs/pages/home/plan.md': '# plan: home\n',
    '.dt.json': '{"team":{}}',
    'src/docs/project-context.md': OLD_PC, // docs/ 밖은 보지 않는다
  });
  try {
    const before = scan(root);
    const st = Object.fromEntries(before.map((f) => [f.path, f.status]));
    assert.equal(st['docs/project-context.md'], 'migrate');
    assert.equal(st['docs/specs/interactions.md'], 'migrate');
    assert.equal(st['docs/specs/pages/home/plan.md'], 'current');
    assert.equal(st['.dt.json'], 'current');
    assert.ok(!('src/docs/project-context.md' in st));
    const preview = apply(root, { write: false });
    assert.equal(readFileSync(join(root, 'docs/project-context.md'), 'utf8'), OLD_PC, '미리보기는 쓰지 않는다');
    assert.equal(preview.previews.length, 2);
    const r = apply(root);
    assert.deepEqual(r.written.sort(), ['docs/project-context.md', 'docs/specs/interactions.md']);
    const pc = readFileSync(join(root, 'docs/project-context.md'), 'utf8');
    assert.match(pc, /## FE 기술 스택\n- React, SCSS/);
    assert.match(pc, /dt-schema: project-context@2/);
    assert.ok(scan(root).every((f) => f.status === 'current'), '다시 점검하면 모두 현재');
    assert.deepEqual(apply(root).written, [], '두 번 돌려도 같다');
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test('migrate: 겹치는 절은 고르기 전에는 쓰지 않고, 더 새 형식은 newer 로 알린다', () => {
  const pc = tmpl('templates/project-context.md.tmpl').replace(/\{\{[A-Z_]+[^}]*\}\}/g, 'x').replace(/<!-- dt-schema[^>]*-->\n/, '') + '\n## Tech Stack\n- SCSS\n';
  const root = project({ 'docs/project-context.md': pc, 'docs/specs/interactions.md': PREAMBLE.replace('@2', '@3') + '## FE 크로스페이지\n### a\n' });
  try {
    const r = apply(root);
    assert.deepEqual(r.written, []);
    assert.match(r.blocked[0].message, /--resolve/);
    assert.equal(scan(root).find((f) => f.kind === 'interactions').status, 'newer');
    const kept = apply(root, { resolve: 'keep' });
    assert.deepEqual(kept.written, ['docs/project-context.md']);
    assert.match(readFileSync(join(root, 'docs/project-context.md'), 'utf8'), /## 옛 기록 — Tech Stack/);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
