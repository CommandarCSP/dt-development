// 헤더 명령줄(GEN-41) — 에이전트가 소스를 읽지 않고 헤더를 만들고, 재결속은 한 줄로 끝낸다.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { runSpecHeaderCli, parseSpecHeader } from '../scripts/buildSpecHeader.mjs';
import { runDefinitionHeaderCli, parseDefinitionHeader, replaceHeaderLines, parseSourceArg } from '../scripts/buildDefinitionHeader.mjs';

const NOW = () => '2026-11-27T00:00:00Z';

test('소스 인자 — URL 안의 : 와 마지막 @역할', () => {
  assert.deepEqual(parseSourceArg('md:docs/req.md@primary'), { type: 'md', locator: 'docs/req.md', role: 'primary' });
  assert.deepEqual(parseSourceArg('figma:https://figma.com/design/A?node-id=1-2@design'), { type: 'figma', locator: 'https://figma.com/design/A?node-id=1-2', role: 'design' });
  assert.deepEqual(parseSourceArg('web:https://a.example/x@y/z'), { type: 'web', locator: 'https://a.example/x@y/z' }, '@ 뒤에 / 가 있으면 역할이 아니다');
  assert.throws(() => parseSourceArg('nocolon'), /type:locator/);
});

test('스펙 헤더 — 새로 만들기는 함수 결과와 같다', () => {
  const { text } = runSpecHeaderCli(['--status', 'draft', '--source', 'as-built:.dt-adopt/extraction.json', '--definition', '../../definition.md@v2', '--if', 'IF-1,IF-3'], { now: NOW });
  assert.match(text, /^<!-- Generated by dt-spec@[\d.]+ at 2026-11-27T00:00:00Z -->/);
  assert.match(text, /<!-- basedOnDefinition: \.\.\/\.\.\/definition\.md@v2 \| IF-1,IF-3 -->/);
  assert.equal(parseSpecHeader(text).sources[0].type, 'as-built');
  assert.match(runSpecHeaderCli(['--status', 'draft', '--source', 'md:a.md', '--sot', 'none'], { now: NOW }).text, /definitionSOT: none/);
  assert.throws(() => runSpecHeaderCli(['--status', 'draft', '--source', 'md:a.md', '--definition', 'x.md'], { now: NOW }), /@v<N>/);
});

test('스펙 헤더 --replace — 정의서 버전만 올리고 상태·소스·IF 목록·다른 주석은 그대로', () => {
  const file = [
    '<!-- origin: as-built @abc123 -->',
    '<!-- Generated by dt-spec@0.15.0 at 2026-11-01T00:00:00Z -->',
    '<!-- status: finalized -->',
    '<!-- sources: as-built:x.json, md:docs/a.md@primary -->',
    '<!-- specVersion: 1.1 -->',
    '<!-- basedOnDefinition: ../../definition.md@v1 | IF-1,IF-2 -->',
    '<!-- scope: comments -->',
    '',
    '# 요구사항',
    '- FR-1 <!-- from: IF-1 -->',
  ].join('\n');
  const r = runSpecHeaderCli(['--replace', 'req.md', '--definition', '../../definition.md@v3'], { readFile: () => file, now: NOW });
  const lines = r.text.split('\n');
  assert.equal(lines[0], '<!-- origin: as-built @abc123 -->');
  assert.ok(r.text.includes('<!-- basedOnDefinition: ../../definition.md@v3 | IF-1,IF-2 -->'));
  assert.ok(r.text.includes('<!-- status: finalized -->') && r.text.includes('md:docs/a.md@primary') && r.text.includes('<!-- scope: comments -->'));
  assert.ok(r.text.endsWith('# 요구사항\n- FR-1 <!-- from: IF-1 -->'), '본문의 주석은 건드리지 않는다');
  assert.equal((r.text.match(/Generated by/g) ?? []).length, 1);
});

test('정의서 헤더 — 새로 만들기와 --replace(버전만)', () => {
  const { text } = runDefinitionHeaderCli(['--status', 'draft', '--source', 'md:docs/req.md@primary', '--source', 'pdf:policy.pdf', '--version', '1'], { now: NOW });
  const h = parseDefinitionHeader(text);
  assert.equal(h.definitionVersion, 1);
  assert.equal(h.sourcesRaw, 'md:docs/req.md@primary, pdf:policy.pdf');
  const r = runDefinitionHeaderCli(['--replace', 'definition.md', '--version', '2', '--status', 'finalized'], { readFile: () => `${text}\n\n## 전역 규약\n`, now: NOW });
  const h2 = parseDefinitionHeader(r.text);
  assert.equal(h2.definitionVersion, 2);
  assert.equal(h2.status, 'finalized');
  assert.equal(h2.sourcesRaw, 'md:docs/req.md@primary, pdf:policy.pdf');
  assert.ok(r.text.endsWith('## 전역 규약\n'));
});

test('헤더 줄이 없는 파일은 맨 앞에 넣는다', () => {
  assert.equal(replaceHeaderLines('# 제목\n', '<!-- status: draft -->', ['status']), '<!-- status: draft -->\n# 제목\n');
});

test('validateDefinition CLI — 결과 JSON 을 출력하고 무효면 종료 코드 1', async () => {
  const { spawnSync } = await import('node:child_process');
  const { mkdtempSync, writeFileSync } = await import('node:fs');
  const { join } = await import('node:path');
  const { tmpdir } = await import('node:os');
  const f = join(mkdtempSync(join(tmpdir(), 'vd-')), 'definition.md');
  writeFileSync(f, '# 비어 있음\n');
  const r = spawnSync('node', [new URL('../scripts/validateDefinition.mjs', import.meta.url).pathname, f], { encoding: 'utf8' });
  assert.equal(r.status, 1);
  assert.equal(JSON.parse(r.stdout).valid, false);
});
