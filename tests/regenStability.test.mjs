// GEN-24 — 같은 입력으로 두 번 돌려도 정의서 버전·플랜이 불필요하게 바뀌지 않는다. 설치 버전은 고정 파일을 따른다.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { nextDefinitionVersion, contractHash } from '../scripts/definitionVersion.mjs';
import { planFreshness, unitSpecHash } from '../scripts/planFreshness.mjs';
import { installList, majorMismatches } from '../scripts/stackVersions.mjs';
import { precheck } from '../scripts/stackPrecheck.mjs';

const DEF = (v, ifRow = '| IF-1 | 주문 생성 `POST /api/v1/orders` | 확정 |', prose = '주문 흐름 정의서.') =>
  `<!-- Generated by dt-devspec@1.0.0 at 2026-11-13T00:00:00Z -->\n<!-- status: finalized -->\n<!-- sources: doc -->\n<!-- specVersion: 1.2 -->\n<!-- definitionVersion: ${v} -->\n\n# 정의서\n\n${prose}\n\n## 전역 규약\n- prefix: /api/v1\n\n## 범위 분담\n| SP-1 | 주문 | BE |\n\n## 인터페이스 합의\n${ifRow}\n\n## 변경 추적\n- 2026-11-13 생성\n`;

test('정의서: 서술·주석·공백만 바뀌면 버전 그대로, 계약(IF·전역 규약)이 바뀌면 +1', () => {
  const old = DEF(3);
  assert.deepEqual(nextDefinitionVersion(old, DEF(3, undefined, '주문 흐름을 다루는 정의서입니다. <!-- 메모 -->')), { current: 3, next: 3, changed: false });
  assert.deepEqual(nextDefinitionVersion(old, DEF(3, '|  IF-1  |  주문 생성 `POST /api/v1/orders`  |  확정  |')), { current: 3, next: 3, changed: false });
  assert.equal(nextDefinitionVersion(old, DEF(3, '| IF-1 | 주문 생성 `PUT /api/v1/orders` | 확정 |')).next, 4);
  assert.equal(nextDefinitionVersion(old, DEF(3).replace('- prefix: /api/v1', '- prefix: /api/v2')).next, 4);
  assert.equal(nextDefinitionVersion('', DEF(1)).next, 1);
  assert.equal(contractHash(DEF(1)), contractHash(DEF(9)), '머리 주석의 버전 숫자는 계약 해시에 들어가지 않는다');
});

test('plan: specHash 가 같으면 fresh, 주석만 바뀌어도 fresh, 본문이 바뀌면 stale', () => {
  const root = mkdtempSync(join(tmpdir(), 'dt-plan-'));
  try {
    const unit = join(root, 'docs/specs/pages/feed');
    mkdirSync(unit, { recursive: true });
    writeFileSync(join(unit, 'requirements.md'), '# R\n### FR-1: a  `[ai-confirmed] [Ubiquitous]`\nTHE SYSTEM SHALL x.\n');
    assert.equal(planFreshness(unit).state, 'missing');
    writeFileSync(join(unit, 'plan.md'), `# plan: feed\n> 출처 스펙: x · specHash: ${unitSpecHash(unit)}\n## Phase 1\n- [ ] a\n`);
    assert.equal(planFreshness(unit).state, 'fresh');
    writeFileSync(join(unit, 'requirements.md'), '# R\n<!-- from: SP-1 -->\n### FR-1: a  `[ai-confirmed] [Ubiquitous]`\n\nTHE SYSTEM SHALL x.\n');
    assert.equal(planFreshness(unit).state, 'fresh', '주석·빈 줄만 바뀐 스펙은 플랜을 다시 만들지 않는다');
    writeFileSync(join(root, 'docs/specs/interactions.md'), '# Interactions\n\n## BE 크로스리소스\n\n### 트랜잭션\n- a\n');
    assert.equal(planFreshness(unit).state, 'fresh', '상대 스택 절은 FE 플랜 해시에 들어가지 않는다');
    writeFileSync(join(unit, 'requirements.md'), '# R\n### FR-1: a  `[ai-confirmed] [Ubiquitous]`\nTHE SYSTEM SHALL y.\n');
    assert.equal(planFreshness(unit).state, 'stale');
  } finally { rmSync(root, { recursive: true, force: true }); }
});

test('stackVersions: 고정 파일에서 설치 목록을 만들고, major 가 다른 패키지를 알려 준다', () => {
  assert.ok(installList('frontend').includes('react@^19'));
  assert.ok(installList('backend', 'devDependencies').includes('prisma@^6'));
  assert.deepEqual(majorMismatches({ dependencies: { 'react-router': '^8.1.0', react: '^19.0.0' } }, 'frontend'), [{ package: 'react-router', expected: '^7', found: '^8.1.0' }]);
  assert.deepEqual(majorMismatches({ dependencies: { 'class-validator': '0.15.1' } }, 'backend'), [{ package: 'class-validator', expected: '^0.14', found: '0.15.1' }]);
  assert.equal(precheck({ dependencies: { react: '19', 'react-router': '^8' } }, 'frontend').versions.length, 1);
});

test('스택 버전 파일: 모든 범위가 major 고정(^N)이고 latest·* 가 없다', () => {
  const v = JSON.parse(readFileSync(new URL('../templates/stack-versions.json', import.meta.url), 'utf8'));
  for (const stack of ['frontend', 'backend']) {
    for (const [k, group] of Object.entries(v[stack])) {
      if (typeof group !== 'object') continue;
      for (const [p, r] of Object.entries(group)) assert.match(r, /^\^\d+(\.\d+)?$/, `${stack}.${k}.${p}: ${r}`);
    }
    assert.match(v[stack].create, /@\d+$/);
  }
});
