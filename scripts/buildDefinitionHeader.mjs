import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const pkg = JSON.parse(readFileSync(new URL('../.claude-plugin/plugin.json', import.meta.url)));
export const PLUGIN_VERSION = pkg.version;
export const SPEC_VERSION = '1.2';

export function buildDefinitionHeader({ generatedAt, status, sources, definitionVersion, scope }) {
  if (status !== 'finalized' && status !== 'draft') {
    throw new Error("status must be 'finalized' or 'draft'");
  }
  if (!Number.isInteger(definitionVersion) || definitionVersion < 1) {
    throw new Error('definitionVersion must be a positive integer');
  }
  const sourcesStr = sources.map(src => {
    let entry = `${src.type}:${src.locator}`;
    if (src.role) entry += `@${src.role}`;
    if (src.loadFailed) entry += ' (load-failed)';
    return entry;
  }).join(', ');

  const lines = [
    `<!-- Generated by dt-devspec@${PLUGIN_VERSION} at ${generatedAt} -->`,
    `<!-- status: ${status} -->`,
    `<!-- sources: ${sourcesStr} -->`,
    `<!-- specVersion: ${SPEC_VERSION} -->`,
    `<!-- definitionVersion: ${definitionVersion} -->`
  ];
  // WHY: scope(옵셔널) — 있을 때만 6번째 줄 emit. 없으면 5줄 유지(하위호환).
  if (scope) {
    lines.push(`<!-- scope: ${scope} -->`);
  }
  return lines.join('\n');
}

// WHY: 헤더 블록 = 파일 최상단 연속 HTML 주석 블록(첫 비-주석/공백 줄에서 종료).
// WHY: buildSpecHeader.parseSpecHeader도 scope 추출에 재사용(DRY) — export.
export function leadingCommentBlock(markdown) {
  const lines = markdown.split('\n');
  const block = [];
  for (const line of lines) {
    if (/^\s*<!--.*-->\s*$/.test(line)) { block.push(line); continue; }
    break; // 첫 비-주석/공백 줄에서 종료
  }
  return block.join('\n');
}

// WHY: specVersion·definitionVersion 줄은 옵셔널(구버전/레거시 generated 대비).
// kind 판정에 쓰는 Generated 마커만 필수 — 없으면 null(=hand-authored).
export function parseDefinitionHeader(markdown) {
  const block = leadingCommentBlock(markdown);
  // kind 판정용 Generated 마커는 정형 마커 줄 전체 앵커(^...$/m)로 매칭 — 부분문자열 contains 금지.
  const gen = block.match(/^\s*<!--\s*Generated by dt-devspec@([\d.]+) at (\S+)\s*-->\s*$/m);
  if (!gen) return null;
  const status = block.match(/<!-- status: (finalized|draft) -->/);
  const sources = block.match(/<!-- sources: (.+?) -->/);
  const spec = block.match(/<!-- specVersion: ([\d.]+) -->/);
  const defVer = block.match(/<!-- definitionVersion: (\d+) -->/);
  const scope = block.match(/<!-- scope: (.+?) -->/);
  return {
    pluginVersion: gen[1],
    generatedAt: gen[2],
    status: status ? status[1] : null,
    sourcesRaw: sources ? sources[1] : null,
    specVersion: spec ? spec[1] : null,
    definitionVersion: defVer ? parseInt(defVer[1], 10) : null,
    scope: scope ? scope[1] : null
  };
}

/**
 * 머리 블록 안의 **헤더 줄만** 새 헤더로 바꾼다. 다른 주석(`<!-- origin: as-built … -->` 따위)은 그 자리에 남긴다.
 * 헤더 줄이 없으면 맨 앞에 넣는다. keys = 헤더 줄 이름(예: 'Generated by', 'status', …).
 */
export function replaceHeaderLines(markdown, header, keys) {
  const lines = markdown.split('\n');
  const isHeader = (l) => keys.some((k) => new RegExp(`^\\s*<!--\\s*${k.replace(/ /g, '\\s+')}\\b`).test(l));
  let end = 0;
  while (end < lines.length && /^\s*<!--.*-->\s*$/.test(lines[end])) end++;
  const first = lines.slice(0, end).findIndex(isHeader);
  if (first < 0) return `${header}\n${markdown}`;
  const kept = lines.slice(0, end).filter((l) => !isHeader(l));
  const before = kept.slice(0, first);
  const after = kept.slice(first);
  return [...before, header, ...after, ...lines.slice(end)].join('\n');
}

/** CLI 인자 — `--key value` 와 같은 키를 여러 번(`--source a --source b`). */
export function parseCliArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) { out._.push(a); continue; }
    const key = a.slice(2);
    const val = argv[i + 1] !== undefined && !argv[i + 1].startsWith('--') ? argv[++i] : true;
    out[key] = key in out ? [].concat(out[key], val) : val;
  }
  return out;
}

/** `type:locator[@role]` → 소스 객체. locator 안의 `:`(URL)는 그대로 둔다 — 역할은 마지막 `@` 뒤. */
export function parseSourceArg(s) {
  const i = s.indexOf(':');
  if (i < 0) throw new Error(`--source 는 type:locator[@role] 형식이다: ${s}`);
  const type = s.slice(0, i); let locator = s.slice(i + 1); let role;
  const at = locator.lastIndexOf('@');
  if (at > 0 && !/[/:]/.test(locator.slice(at + 1))) { role = locator.slice(at + 1); locator = locator.slice(0, at); }
  return { type, locator, ...(role ? { role } : {}) };
}

export const DEFINITION_HEADER_KEYS = ['Generated by', 'status', 'sources', 'specVersion', 'definitionVersion', 'scope'];

/**
 * 명령줄 — 에이전트가 소스를 읽지 않고 헤더를 만들게 한다(GEN-41).
 *   node buildDefinitionHeader.mjs --status draft --source md:<기획서 경로>@primary --version 1 [--scope x] [--generated-at ISO]
 *   node buildDefinitionHeader.mjs --replace docs/specs/definition.md --version 3
 * --replace 는 파일의 헤더 줄만 바꾼다. 빠진 값(status·sources·scope)은 지금 헤더에서 가져온다.
 */
export function runDefinitionHeaderCli(argv, { readFile = (p) => readFileSync(p, 'utf8'), now = () => new Date().toISOString() } = {}) {
  const a = parseCliArgs(argv);
  const cur = a.replace ? parseDefinitionHeader(readFile(a.replace)) : null;
  const sources = a.source ? [].concat(a.source).map(parseSourceArg) : cur?.sourcesRaw ? cur.sourcesRaw.split(', ').map(parseSourceArg) : [];
  const header = buildDefinitionHeader({
    generatedAt: a['generated-at'] ?? now(),
    status: a.status ?? cur?.status,
    sources,
    definitionVersion: Number(a.version ?? cur?.definitionVersion),
    scope: a.scope ?? cur?.scope ?? undefined,
  });
  return a.replace ? { file: a.replace, text: replaceHeaderLines(readFile(a.replace), header, DEFINITION_HEADER_KEYS) } : { text: header };
}

const isMain = (() => { try { return process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url); } catch { return false; } })();
if (isMain) {
  try {
    const r = runDefinitionHeaderCli(process.argv.slice(2));
    if (r.file) { writeFileSync(r.file, r.text); process.stdout.write(`${r.file} — 헤더를 바꿨다\n`); } else process.stdout.write(`${r.text}\n`);
  } catch (e) { process.stderr.write(`❌ ${e.message}\n`); process.exit(2); }
}
